pub async fn schema_snapshot(client: &Client, leave_out: &[&str]) -> Vec<String> {
    let mut snapshot = Vec::new();
    for query in [COLUMNS, CONSTRAINTS, INDEXES] {
        snapshot.extend(texts(client, query, leave_out).await);
    }
    let sequences = client
        .query(SEQUENCES, &[])
        .await
        .expect("read the sequences");
    snapshot.extend(sequences.iter().map(|row| row.get::<_, String>(0)));
    snapshot.sort();
    snapshot
}

async fn texts(client: &Client, query: &str, leave_out: &[&str]) -> Vec<String> {
    client
        .query(query, &[&leave_out])
        .await
        .unwrap_or_else(|err| panic!("{query}: {err:?}"))
        .iter()
        .map(|row| row.get(0))
        .collect()
}

pub async fn goose_era_database(client: &Client, applied: &[i64], recorded: &[i64]) {
    client
        .batch_execute(GOOSE_TABLE)
        .await
        .expect("create goose_db_version");
    record_goose_version(client, 0).await;
    apply_up_sections(client, applied).await;
    for &version in recorded {
        record_goose_version(client, version).await;
    }
}

async fn record_goose_version(client: &Client, version: i64) {
    client
        .execute(RECORD_GOOSE_VERSION, &[&version])
        .await
        .expect("record a goose version");
}

pub async fn apply_up_sections(client: &Client, versions: &[i64]) {
    for version in versions {
        let (_, file) = GOOSE_FILES
            .iter()
            .find(|(known, _)| known == version)
            .unwrap_or_else(|| panic!("no goose file for version {version}"));
        let (up, _) = file
            .split_once("-- +goose Down")
            .expect("a goose Down section");
        client
            .batch_execute(up)
            .await
            .unwrap_or_else(|err| panic!("goose version {version}: {err:?}"));
    }
}

pub async fn seed_rows(client: &Client, per_enrollment: bool) {
    client.batch_execute(SEED).await.expect("seed the rows");
    if per_enrollment {
        client
            .batch_execute(SEED_SECOND_ENROLLMENT)
            .await
            .expect("seed the second enrollment's invoice");
    }
}

pub async fn table_names(client: &Client) -> Vec<String> {
    client
        .query(
            "SELECT tablename::text FROM pg_tables WHERE schemaname = current_schema() ORDER BY 1",
            &[],
        )
        .await
        .expect("list the tables")
        .iter()
        .map(|row| row.get(0))
        .collect()
}

pub async fn rows(client: &Client, table: &str) -> Vec<String> {
    let query = format!("SELECT row_to_json(t)::text FROM {table} t ORDER BY 1");
    client
        .query(&query, &[])
        .await
        .unwrap_or_else(|err| panic!("{query}: {err:?}"))
        .iter()
        .map(|row| row.get(0))
        .collect()
}
